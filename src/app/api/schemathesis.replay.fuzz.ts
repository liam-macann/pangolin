import { describe, test } from 'vitest';

import { readSchemathesisOperations } from '@/test/schemathesis/report';

const operations = readSchemathesisOperations();

// Replay the tests in the above output, through the Vitest reporter
describe('OpenAPI contract fuzzing', () => {
	if (operations.length === 0) {
		test('Loads the report generated by the Schemathesis fixture', () => {
			throw new Error('No Schemathesis report was generated before replay.');
		});
		return;
	}

	operations.forEach(({ errors, failures, name }) => {
		test(name, () => {
			if (failures.length > 0 || errors.length > 0)
				throw new Error([...failures, ...errors].join('\n\n---\n\n'));
		});
	});
});
