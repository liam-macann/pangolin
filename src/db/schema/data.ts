import { eq, getTableColumns, type SQL, sql, sum } from 'drizzle-orm';
import {
	boolean,
	check,
	date,
	foreignKey,
	integer,
	numeric,
	pgEnum,
	pgTable,
	pgView,
	primaryKey,
	text,
	timestamp,
	unique,
	uniqueIndex,
	uuid,
	varchar,
} from 'drizzle-orm/pg-core';

import { users } from './auth';

export const statusEnum = pgEnum('status', ['unpaid', 'paid', 'refunded']);
export const invoices = pgTable(
	'invoice',
	{
		id: uuid().default(sql`uuid_generate_v4()`).primaryKey().notNull(),
		userId: uuid('user_id')
			.notNull()
			.references(() => users.id, { onDelete: 'cascade' }),
		clientData: uuid('client_data_id')
			.notNull()
			.references(() => clientData.id),

		title: varchar('title', { length: 100 }),
		/** Description printed under invoice reference */
		description: text('description'),
		status: statusEnum().notNull(),
		/** Private notes for the user */
		notes: text('notes'),
		/** Whether the invoice has been voided */
		isVoid: boolean('is_void').notNull().default(false),

		/** Timestamp instant of record creation: do not use for invoice display */
		createdAt: timestamp('created_at', { withTimezone: true, mode: 'date' }).notNull().defaultNow(),
		/** Date of invoice issuance in timezone of record
		 *
		 * @remarks This is stored as a date, not a timestamp, to avoid shift on a region redefinition.
		 * Should IANA table change, wall time derived from the creation timestamp becomes unreliable.
		 */
		issuedAt: date('issued_at').notNull(),
		/** Year of invoice issuance in timezone of record, derived from issuedAt */
		issueYear: integer('issue_year')
			.generatedAlwaysAs((): SQL => sql`EXTRACT(YEAR FROM ${invoices.issuedAt})`)
			.notNull(),
		/** Date that payment is due in timezone of record
		 *
		 * @remarks This is stored as a date, not a timestamp, to avoid shift on a region redefinition.
		 * Should IANA table change, wall time derived from the creation timestamp becomes unreliable.
		 */
		dueAt: date('due_at').notNull(),

		/** Sequential index of all invoices generated by user */
		index: integer('index').notNull(),
		/** Sequential index of invoices generated by user in a given issue year (by time zone of record) */
		yearIndex: integer('year_index').notNull(),

		config: uuid('config_id')
			.notNull()
			.references(() => config.id),
	},
	t => [
		foreignKey({
			name: 'invoice_ownership_fk',
			columns: [t.clientData, t.userId],
			foreignColumns: [clientData.id, clientData.userId],
		}),
		// Ensure that the sequence is unique for each user
		unique('user_index').on(t.userId, t.index),
		// Ensure that the yearly sequence is unique for each user, for each year
		uniqueIndex('user_year_yearindex').on(
			t.userId,
			sql`EXTRACT(YEAR FROM ${t.issuedAt})`,
			t.yearIndex,
		),
		check('due_after_issued', sql`${t.dueAt} > ${t.issuedAt}`),
	],
);

export const unitEnum = pgEnum('unit', ['items', 'hours']);
export const invoiceItems = pgTable('invoice_item', {
	id: uuid().default(sql`uuid_generate_v4()`).primaryKey(),
	invoiceId: uuid('invoice_id')
		.notNull()
		.references(() => invoices.id, { onDelete: 'cascade' }),
	/** Invoice entry label */
	label: varchar({ length: 60 }).notNull(),
	/** Optional information to describe the item */
	note: varchar({ length: 60 }),
	quantity: numeric({ precision: 8, scale: 2, mode: 'number' }).notNull(),
	unit: unitEnum(),
	unitCost: numeric('unit_cost', {
		precision: 15,
		scale: 4,
		mode: 'number',
	}).notNull(),
	netAmount: numeric('net_amount', {
		precision: 15,
		scale: 4,
		mode: 'number',
	})
		.generatedAlwaysAs((): SQL => sql`${invoiceItems.quantity} * ${invoiceItems.unitCost}`)
		.notNull(),
	/** Optional sorting index */
	order: integer(),
});

/** Join table for invoice items and taxes */
export const itemTaxes = pgTable(
	'item_tax',
	{
		itemId: uuid('item_id')
			.notNull()
			.references(() => invoiceItems.id, { onDelete: 'cascade' }),
		taxId: uuid('tax_id')
			.notNull()
			.references(() => taxes.id),
	},
	t => [primaryKey({ name: 'item_tax_pkey', columns: [t.itemId, t.taxId] })],
);

// Records should be immutable if referenced
export const taxes = pgTable(
	'tax',
	{
		id: uuid().default(sql`uuid_generate_v4()`).primaryKey(),
		userId: uuid('user_id')
			.notNull()
			.references(() => users.id, { onDelete: 'cascade' }),
		name: varchar({ length: 10 }).notNull(),
		rate: numeric({ precision: 5, scale: 4, mode: 'number' }).notNull(),
		/** True deletion is disallowed. Can be restored on upsert to reduce redundancy. */
		deleted: boolean().notNull().default(false),
		order: integer(),
	},
	t => [
		// Ensure that a user cannot define duplicate taxes (restore deleted records on upsert)
		unique('user_name_rate').on(t.userId, t.name, t.rate),
	],
);

export const invoiceCount = pgTable('invoice_count', {
	userId: uuid('user_id')
		.primaryKey()
		.references(() => users.id, { onDelete: 'cascade' }),
	count: integer().notNull().default(0),
	// Reset with app logic
	yearCount: integer('year_count').notNull().default(0),
	updatedAt: timestamp('updated_at', { withTimezone: true, mode: 'date' }).notNull().defaultNow(),
});

// Logical client. Data is stored in SCD table.
export const clients = pgTable(
	'client',
	{
		id: uuid().default(sql`uuid_generate_v4()`).primaryKey(),
		userId: uuid('user_id')
			.references(() => users.id, { onDelete: 'cascade' })
			.notNull(),
		isFavorite: boolean('is_favorite').notNull().default(false),
		isDeleted: boolean('is_deleted').notNull().default(false),
	},
	// Necessary for ownership constraint on clientData
	t => [unique('client_user_unique').on(t.id, t.userId)],
);

