export const statusEnum = pgEnum('status', ['unpaid', 'paid', 'refunded']);
export const invoices = snakeCase.table(
	'invoice',
	{
		id: uuid().defaultRandom().primaryKey().notNull(),
		userId: uuid()
			.notNull()
			.references(() => users.id, { onDelete: 'cascade' }),
		clientDataId: uuid()
			.notNull()
			.references(() => clientData.id),

		title: varchar({ length: 100 }),
		/** Description printed under invoice reference */
		description: text(),

		/** Timestamp instant of record creation: do not use for invoice display */
		createdAt: timestamp({ withTimezone: true, mode: 'date' }).notNull().defaultNow(),
		/** Date of invoice issuance in timezone of record
		 *
		 * @remarks This is stored as a date, not a timestamp, to avoid shift on a region redefinition.
		 * Should IANA table change, wall time derived from the creation timestamp becomes unreliable.
		 */
		issuedAt: date().notNull(),
		/** Year of invoice issuance in timezone of record, derived from issuedAt */
		issueYear: integer()
			.generatedAlwaysAs((): SQL => sql`EXTRACT(YEAR FROM ${invoices.issuedAt})`)
			.notNull(),
		/** Date that payment is due in timezone of record
		 *
		 * @remarks This is stored as a date, not a timestamp, to avoid shift on a region redefinition.
		 * Should IANA table change, wall time derived from the creation timestamp becomes unreliable.
		 */
		dueAt: date().notNull(),

		/** Sequential index of all invoices generated by user */
		index: integer().notNull(),
		/** Sequential index of invoices generated by user in a given issue year (by time zone of record) */
		yearIndex: integer().notNull(),

		configId: uuid()
			.notNull()
			.references(() => config.id),
	},
	(t): PgTableExtraConfigValue[] => [
		unique('uq_invoice_id_config').on(t.id, t.configId),
		unique('uq_invoice_id_user_id').on(t.id, t.userId),

		// Enforce that client data is owned by the same user as the invoice
		foreignKey({
			name: 'fk_invoice_client',
			columns: [t.clientDataId, t.userId],
			foreignColumns: [clientData.id, clientData.userId],
		}),

		// Enforce 1:1 relationship between invoice and invoice status
		// This must be a deferrable foreign key.
		// Drizzle has no helper for this configuration, so this is implemented through a migration
		foreignKey({
			name: 'fk_invoice_status',
			columns: [t.id],
			foreignColumns: [invoiceStatus.id],
		}),

		// Ensure that the sequence is unique for each user
		unique('uq_invoice_user_index').on(t.userId, t.index),

		// Ensure that the yearly sequence is unique for each user, for each year
		uniqueIndex('uq_user_year_year_index').on(
			t.userId,
			sql`EXTRACT(YEAR FROM ${t.issuedAt})`,
			t.yearIndex,
		),
		check('chk_due_after_issued', sql`${t.dueAt} > ${t.issuedAt}`),

		check('chk_invoice_count_year_index', sql`${t.yearIndex} <= ${t.index}`),
		check('chk_positive_year_index', sql`${t.yearIndex} >= 0`),
		check('chk_positive_index', sql`${t.index} >= 0`),

		policy({
			select: authUid(t.userId),
			insert: authUid(t.userId),
			update: false,
			// Invoices may be voided but not deleted
			delete: false,
		}),
	],
);

export const invoiceStatus = pgTable(
	'invoice_status',
	{
		id: uuid()
			.primaryKey()
			.references(() => invoices.id, { onDelete: 'cascade' }),

		userId: uuid()
			.notNull()
			.references(() => users.id, { onDelete: 'cascade' }),

		/** Invoice payment status.
		 *
		 * @remarks Note that this does not include the invoice void state.
		 * This is intentional, as payment realities may vary (eg. a client may accidentally pay a voided invoice)
		 */
		status: statusEnum().notNull(),
		/** Private notes for the user */
		notes: text(),
		/** Whether the invoice has been voided */
		isVoid: boolean().notNull().default(false),
	},
	t => [
		// Enforce that status data is owned by the same user as the invoice
		foreignKey({
			name: 'fk_invoice_status_invoice',
			columns: [t.id, t.userId],
			foreignColumns: [invoices.id, invoices.userId],
		}),

		policy({
			select: authUid(t.userId),
			insert: authUid(t.userId),
			update: authUid(t.userId),
			delete: false,
		}),
	],
);

export const unitEnum = pgEnum('unit', ['items', 'hours']);
export const invoiceItems = snakeCase.table(
	'invoice_item',
	{
		id: uuid().defaultRandom().primaryKey(),
		invoiceId: uuid()
			.notNull()
			.references(() => invoices.id, { onDelete: 'cascade' }),

		/** Invoice entry label */
		label: varchar({ length: 60 }).notNull(),
		/** Optional information to describe the item */
		note: varchar({ length: 60 }),

		quantity: numeric({ precision: 8, scale: 2, mode: 'number' }).notNull(),
		/** Unit by which quantity is measured. Unitless quantities are valid (eg. 3 hours; 6; 1 item) */
		unit: unitEnum(),
		unitCost: numeric({ precision: 15, scale: 4, mode: 'number' }).notNull(),

		netAmount: numeric({ precision: 15, scale: 4, mode: 'number' })
			.generatedAlwaysAs((): SQL => sql`${invoiceItems.quantity} * ${invoiceItems.unitCost}`)
			.notNull(),

		/** Optional sorting index */
		order: integer(),

		// User ID is propagated down to facilitate ownership constraints
		userId: uuid()
			.notNull()
			.references(() => users.id),
		// Config reference is propagated down to facilitate fk constraints on itemTaxes
		configId: uuid()
			.notNull()
			.references(() => config.id),
	},
	t => [
		unique('uq_invoice_item_id_config').on(t.id, t.configId),

		// Ensure this item references the same config as the associated invoice
		foreignKey({
			name: 'fk_invoice_item_invoice_config',
			columns: [t.invoiceId, t.configId],
			foreignColumns: [invoices.id, invoices.configId],
		}),

		policy({
			select: authUid(t.userId),
			insert: authUid(t.userId),
			// Items must be immutable for stable invoice data
			update: false,
			// Delete only on cascade
			delete: false,
		}),
	],
);

/** Join table for invoice items and taxes */
export const itemTaxes = snakeCase.table(
	'item_tax',
	{
		itemId: uuid()
			.notNull()
			.references(() => invoiceItems.id, { onDelete: 'cascade' }),
		taxId: uuid()
			.notNull()
			.references(() => taxes.id),

		// User ID is stored down to facilitate ownership constraints
		userId: uuid()
			.notNull()
			.references(() => users.id),
		// Config reference is propagated down to facilitate fk constraints
		configId: uuid()
			.notNull()
			.references(() => config.id),
	},
	t => [
		primaryKey({ name: 'item_tax_pkey', columns: [t.itemId, t.taxId] }),

		// Ensure this record references the same config as the associated item
		foreignKey({
			name: 'fk_item_tax_invoice_item',
			columns: [t.itemId, t.configId],
			foreignColumns: [invoiceItems.id, invoiceItems.configId],
		}),

		// Ensure tax is allowed for this configuration
		foreignKey({
			name: 'fk_item_tax_config_tax',
			columns: [t.configId, t.taxId],
			foreignColumns: [configTaxes.configId, configTaxes.taxId],
		}),

		policy({
			select: authUid(t.userId),
			insert: authUid(t.userId),
			// item/tax junction must be stable to prevent invoice totals changing
			update: false,
			// Delete only on cascade
			delete: false,
		}),
	],
);

