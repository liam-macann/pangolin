import { type SQL, sql } from 'drizzle-orm';
import {
	boolean,
	check,
	foreignKey,
	integer,
	numeric,
	pgEnum,
	pgTable,
	primaryKey,
	text,
	timestamp,
	unique,
	uuid,
	varchar,
} from 'drizzle-orm/pg-core';

export const statusEnum = pgEnum('status', ['unpaid', 'paid']);
export const invoices = pgTable(
	'invoice',
	{
		id: uuid().default(sql`uuid_generate_v4()`).primaryKey().notNull(),
		userId: uuid('user_id')
			.notNull()
			.references(() => users.id),
		clientId: uuid('client_id').notNull(),
		title: varchar('title', { length: 100 }),
		description: text('description'),
		status: statusEnum().notNull(),
		createdAt: timestamp('created_at', { withTimezone: true, mode: 'date' }).notNull().defaultNow(),
		dueAt: timestamp('due_at', { withTimezone: true, mode: 'date' })
			.notNull()
			.default(sql`NOW() + INTERVAL '2 weeks'`),
		/** Year, by time zone of record */
		issueYear: integer('issue_year').notNull(),
		/** Sequential index of all invoices generated by user */
		index: integer('index').notNull(),
		/** Sequential index of invoices generated by user in a given issue year (by time zone of record) */
		yearIndex: integer('year_index').notNull(),
		config: uuid('config_id')
			.notNull()
			.references(() => config.id),
	},
	t => [
		foreignKey({
			name: 'client_fk',
			columns: [t.clientId, t.userId],
			foreignColumns: [clients.id, clients.userId],
		}),
		// Ensure that the sequence is unique for each user
		unique('user_index').on(t.userId, t.index),
		unique('user_year_yearindex').on(t.userId, t.issueYear, t.yearIndex),
		check('due_after_created', sql`${t.dueAt} > ${t.createdAt}`),
	],
);

export const unitEnum = pgEnum('unit', ['items', 'hours']);
export const invoiceItems = pgTable('invoice_item', {
	id: uuid().default(sql`uuid_generate_v4()`).primaryKey(),
	invoiceId: uuid('invoice_id')
		.notNull()
		.references(() => invoices.id),
	/** Invoice entry label */
	label: varchar({ length: 60 }).notNull(),
	/** Optional information to describe the item */
	note: varchar({ length: 60 }),
	quantity: numeric({ precision: 8, scale: 2, mode: 'number' }).notNull(),
	unit: unitEnum(),
	unitCost: numeric('unit_cost', {
		precision: 15,
		scale: 4,
		mode: 'number',
	}).notNull(),
	currency: varchar('currency', { length: 3 }).notNull().default('AUD'),
	netAmount: numeric('net_amount', {
		precision: 15,
		scale: 4,
		mode: 'number',
	})
		.generatedAlwaysAs((): SQL => sql`${invoiceItems.quantity} * ${invoiceItems.unitCost}`)
		.notNull(),
	/** Optional sorting index */
	order: integer(),
});

export const invoiceCount = pgTable('invoice_count', {
	userId: uuid('user_id')
		.primaryKey()
		.references(() => users.id),
	count: integer().notNull().default(0),
	// Reset with app logic
	yearCount: integer('year_count').notNull().default(0),
	updatedAt: timestamp('updated_at', { withTimezone: true, mode: 'date' }).notNull().defaultNow(),
});

export const clients = pgTable(
	'client',
	{
		id: uuid().default(sql`uuid_generate_v4()`).unique().notNull(),
		userId: uuid('user_id')
			.notNull()
			.references(() => users.id),
		name: varchar({ length: 255 }).notNull(),
		email: varchar({ length: 255 }).notNull(),
	},
	t => [primaryKey({ name: 'client_user_pk', columns: [t.id, t.userId] })],
);

// Slowly changing dimension (SCD) — history table
export const config = pgTable('config', {
	id: uuid().default(sql`uuid_generate_v4()`).primaryKey(),
	userId: uuid('user_id')
		.notNull()
		.references(() => users.id),
	validFrom: timestamp('valid_from', { withTimezone: true, mode: 'date' }).notNull().defaultNow(),
	validTo: timestamp('valid_to', { withTimezone: true, mode: 'date' }),
	// The time zone of record, for invoice dates and yearly sequencing. This should eventually reference a table of time zones.
	timezone: text().notNull(),
	locale: text().notNull().default('en-AU'),
});

// Auth.js Data

import type { AdapterAccountType } from '@auth/core/adapters';

export const users = pgTable('user', {
	id: uuid().default(sql`uuid_generate_v4()`).primaryKey().notNull(),
	name: text('name').notNull(),
	email: text('email').unique().notNull(),
	password: text(),
	emailVerified: timestamp('email_verified', { mode: 'date' }),
	image: text('image'),
});

export const accounts = pgTable(
	'account',
	{
		userId: uuid('user_id')
			.notNull()
			.references(() => users.id, { onDelete: 'cascade' }),
		type: text('type').$type<AdapterAccountType>().notNull(),
		provider: text('provider').notNull(),
		providerAccountId: text('provider_account_id').notNull(),
		refresh_token: text('refresh_token'),
		access_token: text('access_token'),
		expires_at: integer('expires_at'),
		token_type: text('token_type'),
		scope: text('scope'),
		id_token: text('id_token'),
		session_state: text('session_state'),
	},
	account => [
		{
			compoundKey: primaryKey({
				columns: [account.provider, account.providerAccountId],
			}),
		},
	],
);

export const sessions = pgTable('session', {
	sessionToken: text('sessionToken').primaryKey(),
	userId: uuid('user_id')
		.notNull()
		.references(() => users.id, { onDelete: 'cascade' }),
	expires: timestamp('expires', { mode: 'date' }).notNull(),
});

export const authenticators = pgTable(
	'authenticator',
	{
		credentialID: text('credentialID').notNull().unique(),
		userId: uuid('user_id')
			.notNull()
			.references(() => users.id, { onDelete: 'cascade' }),
		providerAccountId: text('provider_account_id').notNull(),
		credentialPublicKey: text('credential_public_key').notNull(),
		counter: integer('counter').notNull(),
		credentialDeviceType: text('credential_device_type').notNull(),
		credentialBackedUp: boolean('credential_backed_up').notNull(),
		transports: text('transports'),
	},
	authenticator => [
		{
			compositePK: primaryKey({
				columns: [authenticator.userId, authenticator.credentialID],
			}),
		},
	],
);
